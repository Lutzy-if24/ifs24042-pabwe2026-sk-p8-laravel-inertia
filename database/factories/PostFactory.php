<?php

namespace Database\Factories;

use App\Features\Post\Enums\PostCategory;
use App\Features\Post\Models\Post;
use App\Models\User;
use Illuminate\Database\Eloquent\Factories\Factory;

/**
 * @extends Factory<Post>
 */
class PostFactory extends Factory
{
    protected $model = Post::class;

    public function definition(): array
    {
        $title = fake()->sentence(fake()->numberBetween(4, 8));
        $category = fake()->randomElement(PostCategory::cases());

        return [
            'user_id'          => User::factory(),
            'title'            => $title,
            'slug'             => '',  // will be generated by model boot
            'category'         => $category->value,
            'excerpt'          => fake()->paragraph(2),
            'content'          => $this->generateMarkdownContent(),
            'cover_image_path' => null,
            'is_published'     => false,
            'published_at'     => null,
        ];
    }

    public function published(): static
    {
        return $this->state(fn (array $attributes) => [
            'is_published' => true,
            'published_at' => now()->subDays(fake()->numberBetween(1, 30)),
        ]);
    }

    public function draft(): static
    {
        return $this->state(fn (array $attributes) => [
            'is_published' => false,
            'published_at' => null,
        ]);
    }

    public function forUser(User $user): static
    {
        return $this->state(fn (array $attributes) => [
            'user_id' => $user->id,
        ]);
    }

    private function generateMarkdownContent(): string
    {
        $paragraphs = [];
        $paragraphs[] = '## ' . fake()->sentence(5);
        $paragraphs[] = fake()->paragraph(4);
        $paragraphs[] = '### ' . fake()->sentence(4);
        $paragraphs[] = fake()->paragraph(3);
        $paragraphs[] = '- ' . fake()->sentence(6);
        $paragraphs[] = '- ' . fake()->sentence(5);
        $paragraphs[] = '- ' . fake()->sentence(7);
        $paragraphs[] = fake()->paragraph(2);

        return implode("\n\n", $paragraphs);
    }
}
