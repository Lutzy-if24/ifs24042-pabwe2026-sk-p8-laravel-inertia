<?php

namespace App\Features\Post\Services;

use App\Features\Post\Contracts\PostRepositoryInterface;
use App\Features\Post\Models\Post;
use Illuminate\Http\UploadedFile;
use Illuminate\Support\Facades\Storage;

class PostService
{
    public function __construct(
        private readonly PostRepositoryInterface $repository
    ) {}

    public function createPost(int $userId, array $data): Post
    {
        $data['user_id'] = $userId;
        $data['slug']    = '';  // auto-generated by model

        if (isset($data['is_published']) && $data['is_published']) {
            $data['published_at'] = now();
        } else {
            $data['is_published'] = false;
            $data['published_at'] = null;
        }

        return $this->repository->create($data);
    }

    public function updatePost(Post $post, array $data): Post
    {
        // If publish status changes
        if (isset($data['is_published'])) {
            if ($data['is_published'] && !$post->is_published) {
                $data['published_at'] = now();
            } elseif (!$data['is_published']) {
                $data['published_at'] = null;
            }
        }

        return $this->repository->update($post, $data);
    }

    public function deletePost(Post $post): bool
    {
        if ($post->cover_image_path) {
            Storage::disk('public')->delete($post->cover_image_path);
        }
        return $this->repository->delete($post);
    }

    public function togglePublish(Post $post): Post
    {
        $newStatus = !$post->is_published;
        $data = [
            'is_published' => $newStatus,
            'published_at' => $newStatus ? now() : null,
        ];
        return $this->repository->update($post, $data);
    }

    public function uploadCover(Post $post, UploadedFile $file): Post
    {
        // Delete old cover if exists
        if ($post->cover_image_path) {
            Storage::disk('public')->delete($post->cover_image_path);
        }

        $path = $file->store('covers', 'public');

        return $this->repository->update($post, ['cover_image_path' => $path]);
    }

    public function deleteCover(Post $post): Post
    {
        if ($post->cover_image_path) {
            Storage::disk('public')->delete($post->cover_image_path);
        }
        return $this->repository->update($post, ['cover_image_path' => null]);
    }

    public function statsByUser(int $userId): array
    {
        return $this->repository->statsByUser($userId);
    }
}
